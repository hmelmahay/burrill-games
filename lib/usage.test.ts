import assert from "node:assert/strict";
import { usageRoute, deviceType, isDashboardEmail } from "./usage.ts";
import { csvCell, percentage } from "./usage-report.ts";
assert.equal(usageRoute("/quiz/host/SECRET"),"/quiz/host");
assert.equal(usageRoute("/needle/play/ABCD"),"/needle/play");
assert.equal(usageRoute("/admin"),null);
assert.equal(usageRoute("/privacy"),null);
assert.equal(usageRoute("/unknown/person"),null);
assert.equal(usageRoute("/"),"/home");
assert.equal(deviceType(390),"phone");
assert.equal(deviceType(800),"tablet");
assert.equal(deviceType(1200),"desktop");
assert.ok(isDashboardEmail(" Mike@Spille.co "));
assert.ok(!isDashboardEmail("visitor@example.com"));
assert.equal(csvCell('=HYPERLINK("bad")'),'"\'=HYPERLINK(""bad"")"');
assert.equal(csvCell('  +cmd'),'"\'  +cmd"');
assert.equal(csvCell('Steve, "Burr"'),'"Steve, ""Burr"""');
assert.equal(percentage(0,0),null);
assert.equal(percentage(2,3),67);
console.log("16 usage privacy, access-input, and CSV tests passed");
